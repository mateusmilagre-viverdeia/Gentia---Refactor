// Função para obter instruções específicas da página atual
export function getPageInstructions(pathname: string, search: string): string | null {
  const fullPath = `${pathname}${search}`;
  
  // Tentar match exato primeiro
  if (pageInstructions[fullPath]) {
    return pageInstructions[fullPath];
  }
  
  // Tentar só pathname
  if (pageInstructions[pathname]) {
    return pageInstructions[pathname];
  }
  
  // Tentar match por prefixo
  const matchingPath = Object.keys(pageInstructions)
    .filter(path => pathname.startsWith(path.split('?')[0]))
    .sort((a, b) => b.length - a.length)[0];
  
  if (matchingPath) {
    return pageInstructions[matchingPath];
  }
  
  return null;
}
